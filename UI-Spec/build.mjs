import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { tokens, rules, bootstrapVersion, contrastPairs } from './system.mjs';
import {validateRegistry,validateGenerated} from './validate.mjs';
const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
export function cssText() {
  return `/* Generated by UI-Spec/build.mjs. Review UI-Spec/CSS-DECISIONS.md.\n * Bootstrap ${bootstrapVersion} grid subset: MIT; see BOOTSTRAP-LICENSE.txt. */\n` + rules.map(rule => {
    const css = `/* ${rule.id}: ${rule.purpose} */\n${rule.selector} {\n${rule.declarations.map(d => `  ${d.property}: ${d.value}; /* ${d.id} */`).join('\n')}\n}`;
    return rule.media ? `@media ${rule.media} {\n${css}\n}` : css;
  }).join('\n\n') + '\n';
}
function yaml(value, depth = 0) {
  return Object.entries(value).map(([key,item]) => `${'  '.repeat(depth)}${key}:` + (item !== null && typeof item === 'object' ? `\n${yaml(item,depth + 1)}` : ` ${JSON.stringify(item)}`)).join('\n');
}
function cell(value) { return String(value).replaceAll('|','\\|').replaceAll('\n',' '); }
export function ledgerText() {
  return '# CSS declaration decisions\n\nGenerated from [system.mjs](system.mjs). Every declaration has a stable ID, exact value, purpose, user intent and verification family. All decisions are **proposed**, pending maintainer review. Tests establish traceability and observable constraints, not approval of the rationale. Shorthand properties cover every expanded longhand; changing a shorthand value requires reviewing all of its effects.\n\n' + rules.map(rule => `## ${rule.id}\n\nSelector: \`${rule.selector}\`${rule.media ? `; condition: \`${rule.media}\`` : ''}. Source: ${rule.source}. Verification family: \`${rule.check}\`.\n\n| ID | Property | Exact value | Purpose and reason | User intent | Review |\n| --- | --- | --- | --- | --- | --- |\n${rule.declarations.map(d => `| ${[d.id, d.property, d.value, d.purpose, d.intent, d.status].map(cell).join(' | ')} |`).join('\n')}\n`).join('\n');
}
export async function outputs() {
  const body = await readFile(new URL('design-body.md', import.meta.url),'utf8');
  return new Map([
    ['docs/ui-spec/design-system.css',cssText()],
    ['docs/ui-spec/decisions.json',JSON.stringify({ version: 1, bootstrapVersion, rules, contrastPairs },null,2)+'\n'],
    ['UI-Spec/CSS-DECISIONS.md',ledgerText()],
    ['UI-Spec/DESIGN.md',`---\n${yaml(tokens)}\n---\n\n${body}`],
  ]);
}
export async function build() {
  validateRegistry(rules);
  for (const [path, value] of await outputs()) {
    const url = new URL(path,root);
    if (check) validateGenerated(await readFile(url,'utf8'), value, path);
    else { await mkdir(new URL('.',url),{recursive:true}); await writeFile(url,value); }
  }
  console.log(`${check ? 'Checked' : 'Generated'} ${rules.length} rules / ${rules.reduce((n,r)=>n+r.declarations.length,0)} declarations with purpose and intent.`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await build();
